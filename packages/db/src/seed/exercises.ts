export async function seedDevExercises(db: PrismaClient): Promise<number> {
  let created = 0;
  for (const [
    code,
    name,
    category,
    level,
    primaryMuscles,
    secondaryMuscles,
    equipment,
    aliases = [],
  ] of ROWS) {
    const data = {
      name,
      category,
      level,
      primaryMuscles,
      secondaryMuscles,
      equipment,
      aliases,
      searchText: exerciseSearchText({
        name,
        aliases,
        primaryMuscles,
        secondaryMuscles,
        equipment,
      }),
      instructions:
        'Execute com controle, mantendo a postura neutra e respirando ao longo do movimento.',
      tips: 'Ajuste a carga para terminar a série com 1–2 repetições em reserva.',
      commonMistakes: 'Usar impulso, encurtar a amplitude e perder o alinhamento.',
    };
    const exists = await db.exercise.findFirst({ where: { tenantId: null, code } });
    if (exists) continue;
    await db.exercise.create({ data: { ...data, code, tenantId: null } });
    created++;
  }
  return created;
}

